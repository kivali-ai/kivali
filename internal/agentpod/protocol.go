type ArtifactDispatchResponse struct {
	Body    string `json:"body,omitempty"`
	IsError bool   `json:"is_error,omitempty"`
}

// PublishStageRequest is the JSON body of
// POST /v1/agent/{slug}/publish/stage — phase 1 of the two-phase
// publish flow. The agent pod's MCP publish_* tool handlers (notice,
// ceo_approval_request, ceo_notification, the propose_* family) call
// stage first; on success
// they follow up with CommitPublish carrying the returned StageID.
//
// Stage runs the deterministic, non-durable prep work — parse,
// duplicate-role guard, attachment resolution — and persists a staged
// publish record to disk. NO message file is written and NO message
// queue mutation happens at stage time. Stage failures (parse error,
// role conflict, unreachable attachment) surface as IsError=true with
// no staging record created; bridge surfaces straight to the model
// without retry, because the inputs are deterministic.
//
// Tool names match message.ToolsFor's emitted definitions; Input is
// the raw tool arguments JSON the model produced.
type PublishStageRequest struct {
	Tool  string          `json:"tool"`
	Input json.RawMessage `json:"input"`
}

// PublishStageResponse is the response to /publish/stage.
//
// On success: StageID is the opaque identifier the bridge passes to
// /publish/commit; IsError is false; Body is empty (the rendered
// tool_result body is produced at commit time, not stage time, so it
// can reference the queue state observed under the commit lock).
//
// On failure: IsError is true; Body holds the rendered error string
// (model-visible); StageID is empty.
type PublishStageResponse struct {
	StageID string `json:"stage_id,omitempty"`
	Body    string `json:"body,omitempty"`
	IsError bool   `json:"is_error,omitempty"`
}

// PublishCommitRequest is the JSON body of
// POST /v1/agent/{slug}/publish/commit — phase 2 of the two-phase
// publish flow. The bridge sends the StageID returned by stage; the
// server reads the staged publish record, writes the message file at
// its deterministic path, and atomically updates message_queue.json
// (appending the recipient inbox entry AND recording stage_id in the
// queue's CommittedStageIDs set under one lock acquisition).
//
// Commit is idempotent on StageID: any number of retries with the
// same id yields the same Body / IsError. After a transport failure
// the bridge MAY retry commit safely; the server short-circuits on
// the second call because CommittedStageIDs already contains the id.
type PublishCommitRequest struct {
	StageID string `json:"stage_id"`
}

// PublishCommitResponse is the response to /publish/commit. Body is
// the rendered tool_result body; IsError flags tool-level failure
// (route warnings ride on Body with IsError=false, matching the
// in-process behavior — persistence succeeded, route is best-effort).
//
// Distinguishing absences:
//
//   - HTTP 404 / "stage_id not found" — the bridge should NOT
//     interpret this as success; the staged record is missing
//     (expired by janitor, or a stale bridge talking to a fresh
//     core after data wipe). Re-stage and try again.
//   - HTTP 5xx — transport-class failure; retry on the same StageID
//     is safe.
type PublishCommitResponse struct {
	Body    string `json:"body,omitempty"`
	IsError bool   `json:"is_error,omitempty"`
}

// StateDispatchRequest is the JSON body of
// POST /v1/agent/{slug}/state/dispatch. The agent pod's MCP state-
// tools (get_org_chart, list_skills, read_agent_role, the graph reads
// and the assignment tools) all funnel through this one endpoint
// — the server runs the existing rendering logic against the
// authoritative store and returns the model-visible body. Mirrors
// the MemoryDispatch pattern.
//
// Tool-name validation lives server-side; unknown names surface as
// IsError on the response body, not a transport error.
type StateDispatchRequest struct {
	Tool  string          `json:"tool"`
	Input json.RawMessage `json:"input,omitempty"`
}

// StateDispatchResponse mirrors the rendered tool_result envelope:
// Body is the model-visible string, IsError flags tool-level
// failure (CoS-only gate violation, redact target not pending,
// unknown tool, etc.).
type StateDispatchResponse struct {
	Body    string `json:"body,omitempty"`
	IsError bool   `json:"is_error,omitempty"`
}
